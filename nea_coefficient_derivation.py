sqrt_form = np.sqrt(1+Delta)
print(f"  1+Δ/2   = {half_gap:.6f}")
print(f"  √(1+Δ)  = {sqrt_form:.6f}")
print(f"  '1.07'  = {1.07:.6f}   → 与 1+Δ/2 偏差 {abs(1.07-half_gap)/half_gap*100:.2f}%")
print(f"  恒等式 1+Δ/2 = √(1+Δ) + Δ²/8，误差 Δ²/8 = {Delta**2/8:.4f}（相对 {Delta**2/8*100:.2f}%）")
print(f"\n  物理论证：锁定模是振子，ω∝√(刚度)，锁定刚度 ∝ (1+Δ)")
print(f"            → 一切锁定量带因子 √(1+Δ) ≈ 1+Δ/2（缺口由键两端均分）")
for name, formula, val_exp in [
    ("δ_s 味修正",   E0*sqrt_form,        delta_s_exp),
    ("|V_min| 势阱", m_rho*Delta*sqrt_form, 98.0),
]:
    print(f"    {name}: √(1+Δ)版 = {formula:.2f}  (1+Δ/2版 = {formula*half_gap/sqrt_form:.2f})  实验≈{val_exp}")
